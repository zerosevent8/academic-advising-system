/* =========================================================
   results.js — renders the advice generated by advisor.js
   ========================================================= */

document.addEventListener("DOMContentLoaded", () => {
  const mount = document.getElementById("resultsMount");
  if (!mount) return;

  requireAuth();

  const raw = sessionStorage.getItem("aas_last_result");
  if (!raw) {
    mount.innerHTML = "";
    mount.appendChild(
      el("div", { class: "empty-state" }, [
        el("h3", { text: "No advice generated yet" }),
        el("p", { text: "Fill in your academic details to get personalised advice." }),
        el("a", { href: "advisor.html", class: "btn btn-primary", text: "Go to advisor form" }),
      ])
    );
    return;
  }

  const data = JSON.parse(raw);

  const semesterLabel = data.semester === "second" ? "2nd Semester" : "1st Semester";
  const levelLabel = data.level ? `${data.level}L` : "—";

  const flaggedCount = mergeCourseLists(data.carryOverCourses, data.failedCourses).length;

  const summary = el("div", { class: "result-summary" }, [
    statBox(data.gpa.toFixed(2), "GPA"),
    statBox(`${levelLabel} · ${semesterLabel}`, "Level & Semester"),
    statBox(String(data.courseLoad), "New Course Load (units)"),
    statBox(String(flaggedCount), "Flagged Courses"),
  ]);
  mount.appendChild(summary);

  const heading = el("h2", { text: "Your personalised advice" });
  mount.appendChild(heading);

  const recordId = data.id || "legacy";
  const feedbackStore = getFeedbackStore();

  data.advice.forEach((item, index) => {
    const card = el("div", { class: `advice-card flag-${item.flag}` }, [
      el("span", { class: "tag", text: item.tag }),
      el("h3", { text: item.title }),
      el("p", { text: item.body }),
    ]);
    card.appendChild(buildFeedbackWidget(recordId, index, item.tag, feedbackStore));
    mount.appendChild(card);
  });

  const actions = el("div", { class: "form-actions", style: "justify-content:flex-start;" }, [
    el("a", { href: "advisor.html", class: "btn btn-ghost", text: "Run another check" }),
    el("a", { href: "dashboard.html", class: "btn btn-primary", text: "View advice history" }),
  ]);
  mount.appendChild(actions);
});

function statBox(value, label) {
  return el("div", { class: "stat-box" }, [
    el("div", { class: "v", text: value }),
    el("div", { class: "l", text: label }),
  ]);
}

/* ---------- Feedback (thumbs up/down per advice item) ----------
   Stored in localStorage as { "<recordId>_<itemIndex>": "up" | "down" }
   for instant UI state, and also POSTed to the real backend
   (POST /api/feedback) so the department can see which advice
   actually helped students. The backend only stores "up"/"down" —
   toggling a rating off just clears the local UI state, it doesn't
   delete the server-side record. */
const FEEDBACK_STORE_KEY = "aas_feedback";

function getFeedbackStore() {
  try {
    return JSON.parse(localStorage.getItem(FEEDBACK_STORE_KEY)) || {};
  } catch (e) {
    return {};
  }
}

function saveFeedback(recordId, itemIndex, tag, rating) {
  const store = getFeedbackStore();
  store[`${recordId}_${itemIndex}`] = rating;
  localStorage.setItem(FEEDBACK_STORE_KEY, JSON.stringify(store));

  if (rating === "up" || rating === "down") {
    apiFetch("/feedback", {
      method: "POST",
      body: { adviceRecordId: recordId, itemIndex, tag, rating },
    }).catch((err) => {
      console.warn("Feedback didn't reach the server:", err.message);
    });
  }
}

function buildFeedbackWidget(recordId, itemIndex, tag, feedbackStore) {
  const key = `${recordId}_${itemIndex}`;
  let current = feedbackStore[key] || null;

  const upBtn = el("button", { type: "button", class: "feedback-btn", "aria-label": "Mark as helpful" }, [
    el("span", { text: "👍" }),
    el("span", { text: " Helpful" }),
  ]);
  const downBtn = el("button", { type: "button", class: "feedback-btn", "aria-label": "Mark as not helpful" }, [
    el("span", { text: "👎" }),
    el("span", { text: " Not helpful" }),
  ]);
  const thanks = el("span", { class: "feedback-thanks", text: "Thanks for the feedback!" });

  function render() {
    upBtn.classList.toggle("active-up", current === "up");
    downBtn.classList.toggle("active-down", current === "down");
    thanks.classList.toggle("show", Boolean(current));
  }

  upBtn.addEventListener("click", () => {
    current = current === "up" ? null : "up";
    saveFeedback(recordId, itemIndex, tag, current);
    render();
  });
  downBtn.addEventListener("click", () => {
    current = current === "down" ? null : "down";
    saveFeedback(recordId, itemIndex, tag, current);
    render();
  });

  render();

  return el("div", { class: "feedback-row" }, [
    el("span", { class: "feedback-label", text: "Was this advice helpful?" }),
    upBtn,
    downBtn,
    thanks,
  ]);
}
